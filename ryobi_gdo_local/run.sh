#!/usr/bin/with-contenv bashio
# ==============================================================================
# Ryobi GDO Local Server — Home Assistant Add-on entrypoint
#
# This script:
#  1. Reads user options from /data/options.json (set via HA UI)
#  2. Detects the host's LAN IP address (so dnsmasq knows what to advertise)
#  3. Writes a dnsmasq config that resolves tti.tiwiconnect.com → host IP
#  4. Starts dnsmasq in background (DNS server on port 53)
#  5. Writes the ryobi server config from options
#  6. Starts the Python ryobi-local-server in foreground
# ==============================================================================

set -e

bashio::log.info "Starting Ryobi GDO Local Server Add-on..."

# ---------------------------------------------------------------------------
# Read options from HA UI (stored at /data/options.json by Supervisor)
# ---------------------------------------------------------------------------
DEVICE_ID="$(bashio::config 'device_id')"
DEVICE_NAME="$(bashio::config 'device_name' 'Garage Door')"
LOG_LEVEL="$(bashio::config 'log_level' 'info')"
SERVER_PORT="$(bashio::config 'server_port' '80')"
DNS_ENABLED="$(bashio::config 'dns_enabled' 'true')"
DNS_PORT="$(bashio::config 'dns_port' '53')"
COMMAND_WEBHOOK_URL="$(bashio::config 'command_webhook_url' '')"
COMMAND_WEBHOOK_TIMEOUT="$(bashio::config 'command_webhook_timeout' '3')"
FAN_PORTS="$(bashio::config 'fan_ports' '')"
INGRESS_PORT="$(bashio::addon.ingress_port)"

if bashio::var.is_empty "${DEVICE_ID}"; then
    bashio::log.fatal "device_id is required! Set it in the add-on configuration."
    exit 1
fi

bashio::log.info "Device ID:   ${DEVICE_ID}"
bashio::log.info "Device Name: ${DEVICE_NAME}"
bashio::log.info "Server Port: ${SERVER_PORT}"
bashio::log.info "DNS Enabled: ${DNS_ENABLED}"
bashio::log.info "Log Level:   ${LOG_LEVEL}"

# Empty fan_ports keeps the single fan_3 module. "2,5" publishes fan_2 and fan_5.
FAN_YAML='      fan: "fan_3"'
if ! bashio::var.is_empty "${FAN_PORTS}"; then
    FAN_YAML=""
    fan_index=1
    old_ifs="${IFS}"
    IFS=','
    for fan_port in ${FAN_PORTS}; do
        fan_port="$(printf '%s' "${fan_port}" | tr -cd '0-9')"
        if [ -n "${fan_port}" ]; then
            FAN_YAML="${FAN_YAML}      fan${fan_index}: \"fan_${fan_port}\"
"
            fan_index=$((fan_index + 1))
        fi
    done
    IFS="${old_ifs}"
    if [ -z "${FAN_YAML}" ]; then
        FAN_YAML='      fan: "fan_3"'
    fi
fi

# ---------------------------------------------------------------------------
# Detect host LAN IP
# We use the default route interface to find the IP that other LAN devices
# will use to reach this machine (e.g. 192.168.1.100).
# ---------------------------------------------------------------------------
HOST_IP="$(ip route get 1.1.1.1 2>/dev/null | awk '{for(i=1;i<=NF;i++) if ($i=="src") {print $(i+1); exit}}')"
if bashio::var.is_empty "${HOST_IP}"; then
    # Fallback: grab first non-loopback IP
    HOST_IP="$(hostname -i | tr ' ' '\n' | grep -v '^127\.' | grep -v '^::1' | head -1)"
fi

bashio::log.info "Detected host IP: ${HOST_IP}"

# ---------------------------------------------------------------------------
# Configure dnsmasq
# ---------------------------------------------------------------------------
DNSMASQ_CONF="/etc/dnsmasq.d/ryobi.conf"

if [ "${DNS_ENABLED}" = "true" ]; then
    if bashio::var.is_empty "${HOST_IP}"; then
        bashio::log.fatal "Could not detect this machine's LAN IP. DNS cannot be configured."
        exit 1
    fi
    bashio::log.info "Configuring dnsmasq on port ${DNS_PORT}..."

    # Build dnsmasq config:
    # - Resolve tti.tiwiconnect.com → host IP (where our HTTP server runs)
    # - Forward all other DNS to upstream (1.1.1.1 / 8.8.8.8)
    # - Listen on all interfaces so LAN devices can query us
    cat > /etc/dnsmasq.conf <<EOF
# Ryobi GDO Local Server — dnsmasq configuration
# Auto-generated by run.sh — do not edit manually

port=${DNS_PORT}
no-resolv
no-poll

# Upstream DNS servers (used for everything except tti.tiwiconnect.com)
server=1.1.1.1
server=8.8.8.8

# Redirect Ryobi cloud to local server
address=/tti.tiwiconnect.com/${HOST_IP}

# Listen on all interfaces
listen-address=0.0.0.0
bind-interfaces

# Log queries (useful for debugging)
log-queries
log-facility=/proc/1/fd/1

# Reduce TTL so clients pick up changes quickly
local-ttl=10
EOF

    bashio::log.info "Starting dnsmasq..."
    dnsmasq --no-daemon &
    DNSMASQ_PID=$!
    sleep 1
    if ! kill -0 "${DNSMASQ_PID}" 2>/dev/null; then
        bashio::log.fatal "dnsmasq did not stay running. Port ${DNS_PORT} is already in use."
        bashio::log.fatal "AdGuard, Pi-hole, or another DNS add-on is already bound there."
        bashio::log.fatal "Stop that, or set dns_enabled off and add one rewrite on the DNS you already run:"
        bashio::log.fatal "  tti.tiwiconnect.com -> ${HOST_IP}"
        exit 1
    fi
    bashio::log.info "dnsmasq started (PID: ${DNSMASQ_PID})"

    # Also update /etc/resolv.conf inside the addon container so the Python
    # server itself resolves tti.tiwiconnect.com → localhost when cloud_poll is on
    echo "nameserver 127.0.0.1" > /etc/resolv.conf
    echo "nameserver 1.1.1.1" >> /etc/resolv.conf

    bashio::log.info "DNS is running. This add-on is the DNS server for tti.tiwiconnect.com."
    bashio::log.info "Point your router's DNS to: ${HOST_IP}"
    bashio::log.info "Then from another computer on this network run: nslookup tti.tiwiconnect.com"
    bashio::log.info "The answer must be ${HOST_IP}. A public address means that computer is not using this DNS."
    bashio::log.info "In the Ryobi integration set Host to: http://tti.tiwiconnect.com"
else
    bashio::log.info "DNS disabled — skipping dnsmasq."
    bashio::log.info "You must manually redirect tti.tiwiconnect.com -> ${HOST_IP}"
fi

# ---------------------------------------------------------------------------
# Build the ryobi server config file from HA options
# ---------------------------------------------------------------------------
CONFIG_FILE="/data/ryobi_server_config.yaml"

cat > "${CONFIG_FILE}" <<EOF
# Auto-generated by Ryobi GDO Local Server add-on
# Edit via Home Assistant add-on configuration UI, not here.

devices:
  - device_id: "${DEVICE_ID}"
    name: "${DEVICE_NAME}"
    modules:
      garageDoor: "garageDoor_7"
      garageLight: "garageLight_7"
      backupCharger: "backupCharger_6"
      wifiModule: "wifiModule_7"
      parkAssistLaser: "parkAssistLaser_1"
      inflator: "inflator_4"
      btSpeaker: "btSpeaker_2"
${FAN_YAML}

cloud_poll: false
enforce_token: false

$(if ! bashio::var.is_empty "${COMMAND_WEBHOOK_URL}"; then
    echo "command_webhook_url: \"${COMMAND_WEBHOOK_URL}\""
    echo "command_webhook_timeout: ${COMMAND_WEBHOOK_TIMEOUT}"
fi)
EOF

bashio::log.info "Server config written to ${CONFIG_FILE}"

# ---------------------------------------------------------------------------
# Generate SSL certificate for TLS / HTTPS / WSS port 443
# ---------------------------------------------------------------------------
SSL_DIR="/data/ssl"
mkdir -p "${SSL_DIR}"

if [ ! -f "${SSL_DIR}/server.crt" ] || [ ! -f "${SSL_DIR}/server.key" ]; then
    bashio::log.info "Generating self-signed TLS certificate for tti.tiwiconnect.com..."
    openssl req -x509 -newkey rsa:2048 -nodes \
        -keyout "${SSL_DIR}/server.key" \
        -out "${SSL_DIR}/server.crt" \
        -days 3650 \
        -subj "/CN=tti.tiwiconnect.com" \
        -addext "subjectAltName=DNS:tti.tiwiconnect.com,DNS:tti-prod2.thomisidae.com,IP:${HOST_IP}" || true
fi

# The opener checks the server chain against a root it ships with and refuses
# the self-signed certificate. opener_cert_pem takes a full chain (leaf first)
# and opener_key_pem its key; real newlines or literal \n both work.
SSL_CERT="${SSL_DIR}/server.crt"
SSL_KEY="${SSL_DIR}/server.key"
OPENER_CERT_PEM="$(bashio::config 'opener_cert_pem' '')"
OPENER_KEY_PEM="$(bashio::config 'opener_key_pem' '')"
if [ -n "${OPENER_CERT_PEM}" ] && [ -n "${OPENER_KEY_PEM}" ]; then
    printf '%s\n' "${OPENER_CERT_PEM}" | sed 's/\\n/\n/g' > "${SSL_DIR}/opener.crt"
    printf '%s\n' "${OPENER_KEY_PEM}" | sed 's/\\n/\n/g' > "${SSL_DIR}/opener.key"
    chmod 600 "${SSL_DIR}/opener.key"
    SSL_CERT="${SSL_DIR}/opener.crt"
    SSL_KEY="${SSL_DIR}/opener.key"
    bashio::log.info "Opener certificate: $(grep -c 'BEGIN CERTIFICATE' "${SSL_CERT}") in chain, $(openssl x509 -in "${SSL_CERT}" -noout -subject -issuer | tr '\n' ' ')"
fi

# ---------------------------------------------------------------------------
# Start the Ryobi local server (HTTP 80 + HTTPS 443 + Ingress 8099)
# ---------------------------------------------------------------------------
bashio::log.info "Starting Ryobi server on ports ${SERVER_PORT} (HTTP), 443 (HTTPS), and ${INGRESS_PORT} (Ingress)..."

# The real cloud address, resolved past this add-on's own DNS. Phones and
# browsers (they send SNI) are passed straight through to it on 443.
TTI_CLOUD_IP="$(nslookup tti.tiwiconnect.com 1.1.1.1 2>/dev/null \
    | awk '/^Address/ && $2 ~ /^[0-9.]+$/ { ip = $2 } END { print ip }')"
export TTI_CLOUD_IP

# cloud_relay: pass the opener's session through to the real cloud and log it
# (debug level) to learn the protocol.
if bashio::config.true 'cloud_relay'; then
    OPENER_CLOUD_RELAY_IP="${TTI_CLOUD_IP}"
    export OPENER_CLOUD_RELAY_IP
    bashio::log.warning "cloud_relay is on: the opener is relayed to the Ryobi cloud (${OPENER_CLOUD_RELAY_IP:-not resolved}), not controlled locally"
fi

python3 -m server.main \
    --config "${CONFIG_FILE}" \
    --host 0.0.0.0 \
    --port "${SERVER_PORT}" \
    --ssl-port 443 \
    --ssl-cert "${SSL_CERT}" \
    --ssl-key "${SSL_KEY}" \
    --ingress-port "${INGRESS_PORT}" \
    --log-level "$(echo ${LOG_LEVEL} | tr '[:lower:]' '[:upper:]')" &

MAIN_PID=$!
bashio::log.info "Ryobi local server started (PID: ${MAIN_PID})"

bashio::log.info ""
bashio::log.info "Ryobi GDO Local Server is running!"
bashio::log.info "  HTTP:    http://${HOST_IP}:${SERVER_PORT}/api/devices"
bashio::log.info "  HTTPS:   https://${HOST_IP}:443/api/devices"
bashio::log.info "  State:   http://${HOST_IP}:${SERVER_PORT}/state"
bashio::log.info "  Health:  http://${HOST_IP}:${SERVER_PORT}/health"
bashio::log.info ""

# ---------------------------------------------------------------------------
# Keep alive — monitor main server process
# ---------------------------------------------------------------------------
wait ${MAIN_PID}
EXIT_CODE=$?
bashio::log.warning "Ryobi server exited with code ${EXIT_CODE}"

# Clean up dnsmasq if it was started
if [ -n "${DNSMASQ_PID:-}" ]; then
    kill "${DNSMASQ_PID}" 2>/dev/null || true
fi

exit ${EXIT_CODE}
